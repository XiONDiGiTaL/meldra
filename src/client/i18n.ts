const TABLES: Record<Lang, Record<I18nKey, string>> = { en: EN, tr: TR };

let lang: Lang = initialLang(loadSettings());

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang): void {
  if (next !== 'en' && next !== 'tr') return;
  lang = next;
  saveSettings({ lang: next });
  applyI18n();
  document.documentElement.lang = lang;
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  const table = TABLES[lang] ?? EN;
  let text = table[key] ?? EN[key] ?? key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (match, name: string) =>
      vars[name] === undefined ? match : String(vars[name]),
    );
  }
  return text;
}

/** Fills every element carrying data-i18n* attributes in the given subtree. */
export function applyI18n(root: ParentNode = document): void {
  document.documentElement.lang = lang;
  document.title = t('app.title');
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute('content', t('app.description'));

  const nodes = root.querySelectorAll<HTMLElement>(
    '[data-i18n],[data-i18n-placeholder],[data-i18n-title],[data-i18n-aria]',
  );
  nodes.forEach((node) => {
    const key = node.getAttribute('data-i18n');
    const placeholder = node.getAttribute('data-i18n-placeholder');
    const title = node.getAttribute('data-i18n-title');
    const aria = node.getAttribute('data-i18n-aria');
    if (key) node.textContent = t(key as I18nKey);
    if (placeholder) node.setAttribute('placeholder', t(placeholder as I18nKey));
    if (title) node.setAttribute('title', t(title as I18nKey));
    if (aria) node.setAttribute('aria-label', t(aria as I18nKey));
  });
}

export function allKeys(): I18nKey[] {
  return Object.keys(EN) as I18nKey[];
}
